/* EMA PWA: user-initiated install, platform guidance and illustrated launch.
 * Never store mail content, credentials or other private user data here.
 */
(() => {
  "use strict";
  const install = document.getElementById("ema-install-button");
  const dialog = document.getElementById("ema-install-dialog");
  const instructions = document.getElementById("ema-install-instructions");
  const close = document.getElementById("ema-install-close");
  const ok = document.getElementById("ema-install-ok");
  const splash = document.getElementById("ema-pwa-splash");
  let pendingInstall = null;

  const standalone = () =>
    window.matchMedia("(display-mode: standalone)").matches ||
    window.navigator.standalone === true;

  const hideInstall = () => {
    if (install) install.hidden = true;
  };

  function openInstructions(message) {
    if (!dialog || !instructions) return;
    instructions.textContent = message;
    if (typeof dialog.showModal === "function") {
      if (!dialog.open) dialog.showModal();
    } else {
      dialog.setAttribute("open", "");
      dialog.setAttribute("aria-modal", "true");
    }
  }
  function closeInstructions() {
    if (!dialog) return;
    if (typeof dialog.close === "function" && dialog.open) dialog.close();
    else dialog.removeAttribute("open");
  }

  if (install && standalone()) hideInstall();

  window.addEventListener("beforeinstallprompt", (event) => {
    // Chrome/Android allow the native install prompt only on a user click.
    event.preventDefault();
    pendingInstall = event;
    if (install && !standalone()) install.hidden = false;
  });
  window.addEventListener("appinstalled", () => {
    pendingInstall = null;
    hideInstall();
    closeInstructions();
  });

  if (install) install.addEventListener("click", async () => {
    if (standalone()) { hideInstall(); return; }
    if (pendingInstall) {
      const promptEvent = pendingInstall;
      pendingInstall = null; // A deferred install event is single-use.
      try {
        await promptEvent.prompt();
        // Only the browser's appinstalled event confirms installation.
        await promptEvent.userChoice;
      } catch (_) {
        openInstructions("Instalaci se nepodařilo automaticky otevřít. Zkus nabídku prohlížeče → Instalovat aplikaci / Přidat na plochu.");
      }
      return;
    }

    const ua = navigator.userAgent || "";
    const ios = /iPad|iPhone|iPod/i.test(ua) ||
      (navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1);
    if (ios) {
      openInstructions(
        "Na iPhonu nebo iPadu otevři EMU v Safari, klepni na Sdílet a vyber „Přidat na plochu“. Potvrď přidání. iOS nepovoluje přímou instalaci přes tlačítko v aplikaci."
      );
    } else if (/Android/i.test(ua)) {
      openInstructions(
        "Otevři EMU v Chrome, klepni na menu ⋮ a zvol „Nainstalovat aplikaci“ nebo „Přidat na plochu“. Pokud se volba nezobrazuje, zkontroluj HTTPS a instalovatelnost webu."
      );
    } else {
      openInstructions(
        "V prohlížeči Chrome nebo Edge otevři menu ⋮ → Nainstalovat EMA. Pokud je aplikace již nainstalovaná, otevři ji z nabídky aplikací zařízení."
      );
    }
  });
  close?.addEventListener("click", closeInstructions);
  ok?.addEventListener("click", closeInstructions);
  dialog?.addEventListener("click", (event) => {
    if (event.target === dialog) closeInstructions();
  });
  dialog?.addEventListener("cancel", closeInstructions);

  // This is the EMA-branded *in-app* launch screen. The operating-system splash
  // remains generated by the device from the installed manifest icon.
  // Show only once per app window, never on routine page navigation.
  if (splash && standalone()) {
    let shown = false;
    try {
      shown = sessionStorage.getItem("ema.pwa.launch.v1") === "shown";
      if (!shown) sessionStorage.setItem("ema.pwa.launch.v1", "shown");
    } catch (_) {
      // Private mode can disable storage; still permit first-load splash.
    }
    if (!shown) {
      splash.hidden = false;
      const dismiss = () => {
        splash.classList.add("ema-pwa-splash-out");
        window.setTimeout(() => { splash.hidden = true; }, 220);
      };
      // Keep launch brief and never wait for the remote Ema illustration.
      window.setTimeout(dismiss, 900);
    }
  }
})();
